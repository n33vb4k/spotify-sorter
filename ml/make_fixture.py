"""Build web/test/fixtures/pipeline.json from a synthetic signal (no copyrighted audio).

The TypeScript pipeline must reproduce these numbers. Usage:
  PYTHONPATH=ml cli/.venv/bin/python ml/make_fixture.py
"""
import base64, json, os, numpy as np, onnxruntime as ort
from mel_reference import musicnn_bands, mel_filterbank, frames, patches

sr, secs = 16000, 3.0
t = np.arange(int(sr * secs)) / sr
rng = np.random.default_rng(42)
kick = np.sin(2 * np.pi * 55 * t) * np.exp(-((t % 0.5) * 18))           # 120 BPM kick
hats = rng.standard_normal(t.size) * np.exp(-((t % 0.25) * 60)) * 0.15  # 8th-note hats
chirp = 0.2 * np.sin(2 * np.pi * (200 + 1500 * t / secs) * t)
sig = (0.6 * kick + hats + chirp).astype(np.float32)

fb = mel_filterbank()
mel = np.array([musicnn_bands(f, fb) for f in frames(sig)], np.float32)
M = "ml/models/"
act, emb = ort.InferenceSession(M + "discogs-effnet-bsdynamic-1.onnx").run(None, {"melspectrogram": patches(mel)})
relaxed = ort.InferenceSession(M + "mood_relaxed-discogs-effnet-1.onnx").run(None, {"embeddings": emb})[0].mean(0)
pick = [0, 1, 93, len(mel) - 1]
os.makedirs("web/test/fixtures", exist_ok=True)
json.dump({
    "note": "Generated by ml/make_fixture.py from a synthetic signal; reference = numpy port verified against Essentia.",
    "sampleRate": sr,
    "signalF32Base64": base64.b64encode(sig.tobytes()).decode(),
    "numFrames": len(mel), "numPatches": int(len(patches(mel))),
    "filterbankRowSums": [float(x) for x in fb.sum(1)],
    "melFrames": {str(i): [float(x) for x in mel[i]] for i in pick},
    "activationsMean": [float(x) for x in act.mean(0)],
    "relaxedMean": [float(x) for x in relaxed],
}, open("web/test/fixtures/pipeline.json", "w"))
print("frames", len(mel), "patches", len(patches(mel)), "bytes", os.path.getsize("web/test/fixtures/pipeline.json"))
